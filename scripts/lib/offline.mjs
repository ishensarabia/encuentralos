// Browser assets that sit next to the HTML: the guided-questions script, the web app
// manifest and the service worker that keeps the guide usable without signal.

import { createHash } from 'node:crypto';
import { SITE } from '../../site/strings.mjs';

// guide-logic.mjs is written as an ES module for Node; the browser gets a classic
// script (module scripts do not load from file:// and are blocked on some old phones).
export function bundleGuideScript(guideLogic, guideUi) {
  const logic = guideLogic.replace(/^export /gm, '');
  return `(function () {\n'use strict';\n${logic}\n${guideUi}\n})();\n`;
}

function manifest() {
  return JSON.stringify({
    name: SITE.name,
    short_name: SITE.name,
    description: SITE.description,
    lang: 'es-MX',
    start_url: 'index.html',
    scope: './',
    display: 'standalone',
    background_color: '#ffffff',
    theme_color: '#0b5d57',
    icons: [{ src: 'icon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any' }],
  }, null, 2) + '\n';
}

// Network first for pages, so corrected content (e.g. a phone number) shows as soon as
// there is signal; cache first for everything else. The cache name changes whenever
// any file changes, and old caches are deleted on activation.
function serviceWorker(files, version) {
  return `// Generated by scripts/build.mjs. Do not edit.
var CACHE = 'encuentralos-${version}';
var FILES = ${JSON.stringify(files)};

self.addEventListener('install', function (event) {
  event.waitUntil(caches.open(CACHE).then(function (cache) {
    return cache.addAll(FILES);
  }).then(function () { return self.skipWaiting(); }));
});

self.addEventListener('activate', function (event) {
  event.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (key) {
      return key.indexOf('encuentralos-') === 0 && key !== CACHE;
    }).map(function (key) { return caches.delete(key); }));
  }).then(function () { return self.clients.claim(); }));
});

self.addEventListener('fetch', function (event) {
  var request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).then(function (response) {
      if (response.ok) {
        var copy = response.clone();
        caches.open(CACHE).then(function (cache) { cache.put(request, copy); });
      }
      return response;
    }).catch(function () {
      return caches.match(request, { ignoreSearch: true }).then(function (cached) {
        return cached || caches.match('index.html');
      });
    }));
    return;
  }
  event.respondWith(caches.match(request).then(function (cached) {
    return cached || fetch(request);
  }));
});
`;
}

// pages: Map<file, html> from renderSite. Returns the extra files to write.
export function buildAssets(pages, { guideLogic, guideUi, appJs, icon }) {
  const assets = new Map();
  if (pages.has('que-hago.html')) assets.set('guia.js', bundleGuideScript(guideLogic, guideUi));
  assets.set('app.js', appJs);
  assets.set('icon.svg', icon);
  assets.set('manifest.webmanifest', manifest());

  const cached = [...pages.keys(), ...assets.keys()].sort();
  const hash = createHash('sha256');
  for (const file of cached) hash.update(file).update('\0').update(pages.get(file) ?? assets.get(file));
  assets.set('sw.js', serviceWorker(cached, hash.digest('hex').slice(0, 12)));
  return assets;
}
